# Generates hook/gl_stubs.c: forwarding stubs for every opengl32.dll export
# except the ones hook.c implements itself.
import struct, os

HOOKED = {'wglGetProcAddress', 'wglSwapBuffers', 'glBindTexture', 'glDrawArrays', 'glDrawElements'}


def exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    exp_rva = struct.unpack_from('<I', d, pe + 24 + 112)[0]
    secs = []
    for i in range(nsec):
        s = pe + 24 + optsz + i * 40
        vs, va, rs, ra = struct.unpack_from('<IIII', d, s + 8)
        secs.append((va, vs, ra, rs))

    def r2o(rva):
        for va, vs, ra, rs in secs:
            if va <= rva < va + max(vs, rs):
                return rva - va + ra

    o = r2o(exp_rva)
    _, nnames, _, an, _ = struct.unpack_from('<IIIII', d, o + 20)
    out = []
    for i in range(nnames):
        nr = struct.unpack_from('<I', d, r2o(an) + 4 * i)[0]
        out.append(d[r2o(nr):].split(b'\0')[0].decode())
    return out


here = os.path.dirname(os.path.abspath(__file__))
names = [n for n in exports(os.path.join(os.environ['SystemRoot'], 'System32', 'opengl32.dll')) if n not in HOOKED]
NL = '\\n'
Q = '\\"'
lines = ['// Generated by tools/gen_stubs.py - do not edit.', '#include <windows.h>', '']
lines.append('#define STUB_COUNT %d' % len(names))
lines.append('static const char *stub_names[STUB_COUNT] = {')
lines += ['    "%s",' % n for n in names]
lines.append('};')
lines.append('void *stub_ptrs[STUB_COUNT];')
lines.append('')
lines.append('__asm__(')
lines.append('    ".text%s"' % NL)
for i, n in enumerate(names):
    lines.append('    ".globl %s%s%s: jmp *stub_ptrs+%d(%%rip)%s"' % (n, NL, n, i * 8, NL))
lines.append('    ".section .drectve%s"' % NL)
for n in names:
    lines.append('    ".ascii %s -export:%s%s%s"' % (Q, n, Q, NL))
lines.append('    ".text%s"' % NL)
lines.append(');')
lines.append('')
lines.append('int stubs_resolve(HMODULE real) {')
lines.append('    int missing = 0;')
lines.append('    for (int i = 0; i < STUB_COUNT; i++) {')
lines.append('        stub_ptrs[i] = (void *)GetProcAddress(real, stub_names[i]);')
lines.append('        if (!stub_ptrs[i]) missing++;')
lines.append('    }')
lines.append('    return missing;')
lines.append('}')
with open(os.path.join(here, '..', 'hook', 'gl_stubs.c'), 'w', newline='\n') as f:
    f.write('\n'.join(lines) + '\n')
print(len(names), 'stubs')
